import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { before, test } from 'node:test';
import { prepareBrowserTests, useAuthBrowserFixture } from './fixture.mjs';

before(prepareBrowserTests, { timeout: 35000 });

test('the authentication switch persists and credential events log while notifications are disabled', { timeout: 60000 }, async t => {
    const f = await useAuthBrowserFixture(t);
    const { page, context, origin } = f;
    const password = randomBytes(24).toString('base64url');
    await page.getByLabel('Username', { exact: true }).fill('administrator');
    await page.getByLabel('Password', { exact: true }).fill(password);
    await page.getByLabel('Confirm password').fill(password);
    await page.getByRole('button', { name: 'Complete setup' }).click();
    await page.getByLabel('I have saved my recovery key').check();
    await page.getByRole('button', { name: 'Continue', exact: true }).click();
    await page.locator('.shell').waitFor();
    await page.goto(origin + '/notifications', { waitUntil: 'domcontentloaded' });
    const toggle = page.getByRole('checkbox', { name: 'Authentication notifications', exact: true });
    await toggle.waitFor();
    assert.equal(await toggle.isChecked(), false);
    assert.equal(await page.getByRole('checkbox', { name: /Authentication/ }).count(), 1);
    await toggle.check();
    await page.getByRole('button', { name: 'Save', exact: true }).click();
    await page.getByText('Notification settings saved', { exact: true }).waitFor();
    const stored = JSON.parse(await readFile(f.env.NOTIFICATIONS_CONFIG_PATH, 'utf8'));
    assert.equal(stored.enabled, false);
    assert.equal(stored.provider, 'ntfy');
    assert.equal(stored.triggers.authentication, true);
    await f.restart();
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.getByLabel('Username', { exact: true }).fill('administrator');
    await page.getByLabel('Password', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await page.locator('.shell').waitFor();
    await page.goto(origin + '/notifications', { waitUntil: 'domcontentloaded' });
    await toggle.waitFor();
    assert.equal(await toggle.isChecked(), true);
    await page.setViewportSize({ width: 390, height: 844 });
    await toggle.scrollIntoViewIfNeeded();
    assert(await toggle.isVisible());
    await toggle.uncheck();
    await page.getByRole('button', { name: 'Save', exact: true }).click();
    await page.getByText('Notification settings saved', { exact: true }).waitFor();
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.getByRole('button', { name: 'Sign out', exact: true }).click();
    await page.getByLabel('Username', { exact: true }).fill('administrator');
    await page.getByLabel('Password', { exact: true }).fill(randomBytes(24).toString('base64url'));
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Login failed' }).waitFor();
    await page.getByLabel('Password', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await page.locator('.shell').waitFor();
    const response = await context.request.get(origin + '/api/logs/app');
    assert.equal(response.status(), 200);
    const entries = (await response.json()).entries.filter(entry => entry.event === 'authentication');
    assert(entries.some(entry => entry.method === 'password' && entry.outcome === 'failure' && entry.level === 'warn'));
    assert(entries.some(entry => entry.method === 'password' && entry.outcome === 'success' && entry.level === 'info'));
    assert(!JSON.stringify(entries).includes(password));
    assert.equal(JSON.parse(await readFile(f.env.NOTIFICATIONS_CONFIG_PATH, 'utf8')).triggers.authentication, false);
});
